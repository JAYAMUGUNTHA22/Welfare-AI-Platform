const commonTags = ['agriculture-rural-environment', 'farmer'];

function privateProgramme({
  schemeId, name, provider, website, overview, benefits, beneficiaries,
  eligibility, locations, crops = [], locationNotes = '', cropsNeedConfirmation = false,
  states = [], districts = [],
}) {
  return {
    schemeId,
    name,
    provider,
    providerType: 'NGO/Foundation',
    recommendationGroup: 'private',
    category: 'agriculture-rural-environment',
    tags: commonTags,
    overview,
    benefitSummary: benefits.join(' '),
    benefits,
    targetBeneficiaries: beneficiaries,
    eligibility,
    supportedLocations: locations,
    supportedCrops: crops,
    officialWebsite: website,
    activeStatus: 'unconfirmed',
    verification: 'official_program_information_reviewed_availability_unconfirmed',
    applicationMethod: 'Contact the provider through its official website to confirm current local availability and participation requirements.',
    supportMetadata: {
      kind: 'farmer_programme',
      availabilityNote: 'The organization describes this programme publicly; current intake and individual eligibility must be confirmed with the provider.',
      locationNotes,
      supportedStates: states,
      supportedDistricts: districts,
      cropsNeedConfirmation,
      incomeRule: 'No income threshold was stated on the cited official programme page.',
    },
  };
}

